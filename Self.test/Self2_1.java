public class Self2_1 {

    public static void main(String[] args) {

        // ①int型の hogeInt という名前の変数を宣言し、値「100」で初期化
        int hogeInt = 100;

        // ②Stringクラスの hogeString という名前の変数を宣言、値「テスト」で初期化
        String hogeString = "テスト";

        // ③double型の変数hogeDoubleを宣言し、10で初期化している
        double hogeDouble = 10.0;

        // ④変数 hogeInt を値「100」で上書き
        hogeInt = 100;

        // ⑤変数 hogeString を値「頑張りました！」で上書き
        hogeString = "頑張りました！";

        // ⑥変数 hogeInt の値を表示
        System.out.println(hogeInt);

        // ⑦変数hogeStringの値（文字列）をコンソールに出力している
        System.out.println(hogeString);

        // ⑧変数 hogeDouble の値を表示
        System.out.println(hogeDouble);

    }
    
}
